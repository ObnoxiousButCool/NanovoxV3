"""Password hashing for the single shared login credential.

Unlike the six-digit OTP this replaces (`domain.value_objects.otp_code`,
removed with it), a password is long-lived and was not generated by a
cryptographic RNG, so a fast hash is the wrong tool — it is exactly the
kind of secret a slow, salted KDF exists to protect. PBKDF2-HMAC-SHA256 at
OWASP's current recommended iteration count, stdlib only.

The stored form is ``salt_hex$derived_hex``, so the salt travels with the
hash rather than needing its own column.
"""

from __future__ import annotations

import hashlib
import hmac
import os

_ALGORITHM = "sha256"
_ITERATIONS = 600_000
_SALT_BYTES = 16


def hash_password(password: str) -> str:
    salt = os.urandom(_SALT_BYTES)
    derived = hashlib.pbkdf2_hmac(_ALGORITHM, password.encode("utf-8"), salt, _ITERATIONS)
    return f"{salt.hex()}${derived.hex()}"


def password_matches(password: str, *, hashed: str) -> bool:
    """Constant-time comparison. Returns `False` for a malformed stored hash
    rather than raising — a corrupt setting should fail closed, not 500."""
    salt_hex, separator, derived_hex = hashed.partition("$")
    if not separator:
        return False
    try:
        salt = bytes.fromhex(salt_hex)
        expected = bytes.fromhex(derived_hex)
    except ValueError:
        return False
    candidate = hashlib.pbkdf2_hmac(_ALGORITHM, password.encode("utf-8"), salt, _ITERATIONS)
    return hmac.compare_digest(candidate, expected)
